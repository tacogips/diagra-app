import { expect, test } from "bun:test";
import { Database } from "bun:sqlite";
import type { ErdTableSemantic } from "@diagra/ir";
import { applyErdDefinition } from "./erd-definition-edit.ts";
import { parseErdDefinition } from "./erd-definition.ts";
import { generateDatabaseDdl } from "./database-ddl.ts";
import { document, erdFixture, makeEditor } from "./test-helpers.ts";

test("text apply preserves referenced IDs, rejects stale input and has one undo", () => {
  const editor = makeEditor({ document: document(erdFixture()) });
  const baseline = JSON.stringify(editor.store.get("users")?.semantic);
  expect(
    applyErdDefinition(
      editor,
      "users",
      "renamed_id UUID PRIMARY KEY",
      "postgresql",
      baseline,
    ),
  ).toBeUndefined();
  expect(
    (editor.store.get("users")?.semantic as ErdTableSemantic).columns[0]?.id,
  ).toBe("c1");
  expect(
    applyErdDefinition(editor, "users", "id text", "postgresql", baseline),
  ).toContain("changed");
  editor.undo();
  expect(JSON.stringify(editor.store.get("users")?.semantic)).toBe(baseline);
  editor.redo();
  const current = JSON.stringify(editor.store.get("users")?.semantic);
  expect(
    applyErdDefinition(editor, "users", "", "postgresql", current),
  ).toContain("relations");
  expect(JSON.stringify(editor.store.get("users")?.semantic)).toBe(current);
});

test("all nine input/output dialect combinations retain identity and SQLite executes", () => {
  const inputs = {
    postgresql: "id SERIAL PRIMARY KEY, name varchar(256) NOT NULL",
    mysql: "id integer AUTO_INCREMENT PRIMARY KEY, name varchar(256) NOT NULL",
    sqlite: "id INTEGER PRIMARY KEY AUTOINCREMENT, name varchar(256) NOT NULL",
  } as const;
  for (const input of ["postgresql", "mysql", "sqlite"] as const) {
    const parsed = parseErdDefinition(inputs[input], input);
    expect(parsed.error).toBeUndefined();
    const editor = makeEditor();
    const table = editor.buildElement("erd.table", {
      id: "people",
      semantic: {
        tableName: "people",
        columns: parsed.columns?.map((column, i) => ({
          ...column,
          id: `c${i}`,
        })),
      },
    });
    editor.apply([{ type: "createElement", element: table }]);
    for (const output of ["postgresql", "mysql", "sqlite"] as const) {
      const result = generateDatabaseDdl(editor, editor.currentPageId, output);
      expect(result.warnings).toEqual([]);
      expect(result.sql).toContain(
        output === "postgresql"
          ? "GENERATED BY DEFAULT AS IDENTITY"
          : output === "mysql"
            ? "AUTO_INCREMENT"
            : "INTEGER PRIMARY KEY AUTOINCREMENT",
      );
      expect(result.sql.endsWith("\n")).toBe(true);
      if (output === "sqlite") {
        const db = new Database(":memory:");
        try {
          db.exec(result.sql);
          db.exec("INSERT INTO people(name) VALUES ('one'), ('two');");
          expect(db.query("SELECT id FROM people ORDER BY id").all()).toEqual([
            { id: 1 },
            { id: 2 },
          ]);
        } finally {
          db.close();
        }
      }
    }
  }
});

test("text apply rejects changed dialect and dependent index deletion atomically", () => {
  const editor = makeEditor();
  const table = editor.buildElement("erd.table", {
    id: "t",
    semantic: {
      tableName: "t",
      columns: [
        { id: "a", name: "a", dataType: "integer" },
        { id: "b", name: "b", dataType: "text" },
      ],
      indexes: [{ id: "idx", columns: ["b"] }],
    },
  });
  editor.apply([{ type: "createElement", element: table }]);
  const baseline = JSON.stringify(table.semantic);
  expect(
    applyErdDefinition(editor, "t", "a integer", "postgresql", baseline),
  ).toContain("indexes");
  expect(
    applyErdDefinition(
      editor,
      "t",
      "x integer, y text",
      "postgresql",
      baseline,
    ),
  ).toContain("one column");
  editor.setPageSqlDialect(editor.currentPageId, "sqlite");
  expect(
    applyErdDefinition(
      editor,
      "t",
      "a integer, b text",
      "postgresql",
      baseline,
    ),
  ).toContain("dialect changed");
  expect(JSON.stringify(editor.store.get("t")?.semantic)).toBe(baseline);
});

test("export is invariant under canvas stacking and record insertion order", () => {
  const original = erdFixture();
  const a = makeEditor({ document: document(original) });
  const b = makeEditor({
    document: document(
      [...original].reverse().map((element, i) => ({
        ...element,
        index: `a${i}`,
        visual: { ...element.visual, x: 900 - i * 50 },
      })),
    ),
  });
  for (const dialect of ["postgresql", "mysql", "sqlite"] as const) {
    expect(generateDatabaseDdl(a, a.currentPageId, dialect).sql).toBe(
      generateDatabaseDdl(b, b.currentPageId, dialect).sql,
    );
  }
});

test("index and check declaration order does not affect SQL", () => {
  const original = erdFixture().map((element) =>
    element.id !== "users"
      ? element
      : {
          ...element,
          semantic: {
            ...(element.semantic as ErdTableSemantic),
            indexes: [
              { id: "ix-z", name: "z_index", columns: ["c1"] },
              { id: "ix-a", name: "a_index", columns: ["c1"] },
            ],
            checks: [
              { id: "ck-z", name: "z_check", expression: "id IS NOT NULL" },
              { id: "ck-a", name: "a_check", expression: "id IS NOT NULL" },
            ],
            columns: (element.semantic as ErdTableSemantic).columns.map(
              (column) => ({ ...column, pk: false }),
            ),
          },
        },
  );
  const reversed = original.map((element) =>
    element.id !== "users"
      ? element
      : {
          ...element,
          semantic: {
            ...(element.semantic as ErdTableSemantic),
            indexes: [
              ...((element.semantic as ErdTableSemantic).indexes ?? []),
            ].reverse(),
            checks: [
              ...((element.semantic as ErdTableSemantic).checks ?? []),
            ].reverse(),
          },
        },
  );
  const a = makeEditor({ document: document(original) });
  const b = makeEditor({ document: document(reversed) });
  for (const dialect of ["postgresql", "mysql", "sqlite"] as const) {
    const sql = generateDatabaseDdl(a, a.currentPageId, dialect).sql;
    expect(sql).toBe(generateDatabaseDdl(b, b.currentPageId, dialect).sql);
    expect(sql.indexOf("a_index")).toBeLessThan(sql.indexOf("z_index"));
    expect(sql.indexOf("a_check")).toBeLessThan(sql.indexOf("z_check"));
  }
});
